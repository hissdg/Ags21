#!/usr/bin/env bash
# ============================================================================
#  AGS21 —— GitHub Actions 构建入口（本地也能跑，方便先验证）
#
#  设计原则：补丁逻辑只维护一份。
#  本脚本不自己实现「放 dts / 改 filogic.mk / 改 02_network / 改 platform.sh」，
#  而是直接调 build/build-ags21.sh。这样「本地编出来」和「CI 编出来」是同一个东西，
#  不会出现两边补丁悄悄分叉、本地能编 CI 编不过的情况。
#
#  流程：
#    ① build-ags21.sh --stage=sync   拉源码 + 放 dts + 打补丁   （秒级，幂等）
#    ② 把 ci/config.seed 铺成 .config （含 CONFIG_CCACHE=y）
#    ③ 装 feeds（luci / packages / routing 都在 feed 里，不在源码树里）
#    ④ build-ags21.sh --stage=all    完整编译
#    ⑤ 自检：产物存在 / sha256 / FIT 配置名必须是 config-1
#
#  为什么绕一圈（①②③④）而不是直接 --stage=all：
#    build-ags21.sh 的配置段现在是「必选项清单，缺哪行补哪行」，不会覆盖已有的 .config，
#    所以先把 seed 铺好（②）再跑 ④，两边合起来正好是我们要的配置。
#    另外 CONFIG_CCACHE=y 只在 seed 里 —— build-ags21.sh 那份清单故意不含 ccache，
#    本地编译不需要它，云编译才需要。
#
#  关于 feeds（③）：为什么这儿再显式装一次
#    build-ags21.sh 里原来那段是死代码（`[ -d feeds ] && [ ! -d feeds/luci ]`
#    首次 clone 后两个条件永远同时为假），2026-10-12 已改成 `[ ! -d feeds/luci ]`，
#    所以脚本本身现在也会装。CI 这里保留独立的 ③ 是有意的：
#      1) 顺序保证 —— feeds 必须在 `make defconfig` 之前就位，否则 config.seed 里
#         feed 的包（CONFIG_PACKAGE_luci=y）解析不出来，会被 defconfig 静默丢掉。
#         放在 ④ 之前，这个顺序是明摆着的，不依赖脚本内部的先后。
#      2) 拉 feed 是几分钟的网络操作，单独成步后，失败时能在日志里一眼区分
#         「网络慢 / 拉不到源」和「编译报错」。
#    两边判断都是「没有才装」，重复执行只多一次目录检查，没有代价。
#
#  用法：
#    bash ci/ci-build.sh              # 完整编译出 sysupgrade.itb
#    bash ci/ci-build.sh --dtb        # 只验设备树（分钟级，不编内核，不装 feeds）
#    bash ci/ci-build.sh --sync       # 只拉源码打补丁
#    AGS21_WORKDIR=~/foo bash ci/ci-build.sh
# ============================================================================
set -Eeuo pipefail

# ---------------------------------------------------------------- 错误可见性
# 背景（实测）：GET /repos/{o}/{r}/actions/jobs/{id}/logs 需要仓库 admin 权限，
#   公开仓库同样返回 403 "Must have admin rights to Repository"。
#   公开可读的只有 check-run annotations，里面只认 ::error:: / ::warning::。
#   ⇒ 失败时必须打 ::error::，否则远程只能看到一句
#     "Process completed with exit code 1."，等于没有线索。
on_err() {
	local rc=$? line=${BASH_LINENO[0]:-?} cmd=${BASH_COMMAND:-?}
	# GitHub 注释体里的换行要写成 %0A，否则只显示第一行
	printf '::error file=ci/ci-build.sh,line=%s::第 %s 行失败（exit %s）：%s\n' \
		"$line" "$line" "$rc" "${cmd//$'\n'/%0A}"
	exit "$rc"
}
trap on_err ERR

# ---------------------------------------------------------------- 变量
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OWRT="${AGS21_WORKDIR:-$HOME/openwrt-ags21}"
SEED="$ROOT/ci/config.seed"
BUILDER="$ROOT/build/build-ags21.sh"
LOG="$ROOT/ags21-build.log"

STAGE=all
case "${1:-}" in
	--all)  STAGE=all  ;;
	--dtb)  STAGE=dtb  ;;
	--sync) STAGE=sync ;;
	"")    STAGE=all  ;;
	*)     echo "未知参数：$1（可用 --all / --dtb / --sync）" >&2; exit 2 ;;
esac

step() { printf '\n\033[1;36m### %s\033[0m\n' "$*"; }

echo "AGS21 CI 构建   stage=$STAGE"
echo "  仓库根 : $ROOT"
echo "  源码树 : $OWRT"
echo "  日志   : $LOG"

# ---------------------------------------------------------------- 体检
step "环境体检"
echo "  CPU      : $(nproc) 核"
echo "  内存     : $(awk '/MemTotal/{printf "%.1f GB", $2/1048576}' /proc/meminfo)"
FREE_GB=$(( $(df -Pk "$HOME" | awk 'NR==2{print $4}') / 1048576 ))
echo "  可用空间 : ${FREE_GB} GB（完整编译要 20-25 GB）"
if [ "$STAGE" = "all" ] && [ "$FREE_GB" -lt 18 ]; then
	printf '::warning::可用空间只剩 %s GB，完整编译大概率会 ENOSPC。\n' "$FREE_GB"
	printf '::warning::检查 workflow 里的「腾出磁盘空间」步骤是否还在正常执行。\n'
fi
[ -f "$BUILDER" ] || { printf '::error::找不到 %s\n' "$BUILDER"; exit 1; }

# ---------------------------------------------------------------- ① 源码树 + 补丁
step "① 准备源码树并打补丁（复用 build/build-ags21.sh，幂等）"
# 这一步会 clone openwrt v25.12.5、装 feeds，并打四处补丁 + 往 luci-mod-status 注入两行，输出里会列出补丁命中情况。
# 补丁锚点对不上时它自己会明确报错退出（而不是乱改上游文件），正合我们要的。
bash "$BUILDER" --stage=sync --workdir="$OWRT"

# sync 到此为止。不加这个短路的话会掉进下面的 ③ 再跑一遍 sync，
# 顺带打出一个名不副实的「编译」小标题。
if [ "$STAGE" = "sync" ]; then
	step "stage=sync 完成：源码就绪，四处补丁 + 一处注入已在上游文件上干净应用"
	exit 0
fi

# ---------------------------------------------------------------- ② .config
if [ "$STAGE" != "sync" ]; then
	step "② 写入 .config（来自 ci/config.seed）"
	[ -f "$SEED" ] || { printf '::error::找不到 %s\n' "$SEED"; exit 1; }
	[ -d "$OWRT" ] || { printf '::error::%s 不存在，第①步没成功\n' "$OWRT"; exit 1; }

	# 覆盖写而不是追加：缓存恢复后可能残留上一轮的 .config，
	# 种子是唯一真源，每次从零生成才是确定的。
	# 生成的首行注释刻意用 ASCII：这个文件要整份喂给 Kconfig 解析器，
	# 而 runner 的 locale 可能是 C，不想在非 ASCII 上冒任何险
	# （config.seed 本身也据此保持纯 ASCII，中文说明在 ci/README.md）。
	{
		echo "# Generated by ci/ci-build.sh from ci/config.seed -- edit config.seed, not this file"
		cat "$SEED"
	} >"$OWRT/.config"
	echo "  种子明细："
	sed 's/^/    /' <"$OWRT/.config"
fi

# ---------------------------------------------------------------- ③ feeds
# 只在完整编译时装：--dtb 的价值就是「几秒钟出结果」，不该为它多花几分钟拉 feed。
if [ "$STAGE" = "all" ]; then
	step "③ 安装 feeds（luci / packages / routing ... 都在 feed 里，不在源码树里）"
	if [ -d "$OWRT/feeds/luci" ]; then
		echo "  已存在，跳过：$OWRT/feeds/luci"
	else
		# 见文件头「关于 feeds（③）」——顺序与可观测性上的理由，不是重复劳动
		(cd "$OWRT" && ./scripts/feeds update -a && ./scripts/feeds install -a)
	fi
fi

# ---------------------------------------------------------------- ④ 编译
step "④ 编译（stage=$STAGE）"
# 滤掉 build-ags21.sh 的 ANSI 色码，CI 日志才干净（本地看还是彩色的）
set +e
bash "$BUILDER" --stage="$STAGE" --workdir="$OWRT" 2>&1 \
	| sed -u 's/\x1b\[[0-9;]*m//g' \
	| tee "$LOG"
RC=${PIPESTATUS[0]}
set -e
if [ "$RC" -ne 0 ]; then
	printf '::error::构建失败（exit %s）。完整日志见 artifact「ags21-build.log」，或看上方 # 分组里最后出错的那一段。\n' "$RC"
	exit "$RC"
fi

# ---------------------------------------------------------------- ⑤ 自检
if [ "$STAGE" != "all" ]; then
	step "（stage=$STAGE 到此为止，没有完整固件产物）"
	exit 0
fi

step "⑤ 检查产物"
BIN="$OWRT/bin/targets/mediatek/filogic"
shopt -s nullglob
ITBS=("$BIN"/*aigo_ags21*.itb)

if [ "${#ITBS[@]}" -eq 0 ]; then
	printf '::error::没找到 *aigo_ags21*.itb。%s 的内容：\n' "$BIN"
	ls -l "$BIN" 2>/dev/null | head -40 || true
	exit 1
fi

# 挑出 sysupgrade（升级用）；顺带记下 recovery（initramfs，救砖用）
SUP=""
for f in "${ITBS[@]}"; do
	case "$f" in *sysupgrade*) SUP="$f" ;; esac
done
[ -n "$SUP" ] || SUP="${ITBS[0]}"

echo "  FIT 自检（必须只有 config-1，原因见 build/README.md 第 3 节）："
FITOUT="$(python3 "$ROOT/build/fit_configs.py" "$SUP")" || {
	printf '::error::fit_configs.py 解析 %s 失败\n' "$SUP"; exit 1
}
# 完整输出留进日志文件（artifact 里能翻），屏幕上只放 configurations 那几行
printf '%s\n' "$FITOUT" >>"$LOG"
printf '%s\n' "$FITOUT" | sed -n '/=== configurations ===/,/^$/p' | sed 's/^/    /'

# 为什么是「数条数」而不是「取第一个值」：
#   实测官方 RAX3000M 的 itb，fit_configs.py 会给出三条 setenv 建议
#   （config-1 和两个 overlay 各一条）。如果只取第一条判断，那么一个
#   「base + overlay」的多配置镜像也会提取出 config-1 然后顺利通过 —— 漏报。
#   我们的设计是单 DTS、无 overlay，所以条数必须恰好是 1。
BOOTCONF_N="$(printf '%s\n' "$FITOUT" | grep -c "setenv bootconf '" || true)"
BOOTCONF="$(printf '%s\n' "$FITOUT" | sed -n "s/.*setenv bootconf '\([^']*\)'.*/\1/p" | head -1)"

if [ "$BOOTCONF_N" -eq 1 ] && [ "$BOOTCONF" = "config-1" ]; then
	echo "  ✓ FIT 只有 config-1 一个配置节点，与预期一致（单 DTS、无 overlay）"
else
	printf '::error::FIT 自检没过：setenv 建议 %s 条（预期 1），第一个值是 %q（预期 config-1）\n' \
		"$BOOTCONF_N" "$BOOTCONF"
	printf '::error::多半是 dts 或 filogic.mk 被动过 —— 例如误加 DEVICE_DTS_OVERLAY，\n'
	printf '::error::会让 FIT 变成 base+overlay 多配置，bootconf 就不能是 config-1 了。\n'
	exit 1
fi

{
	echo
	echo "## AGS21 构建产物"
	echo
	echo "| 文件 | 大小 | SHA256 |"
	echo "|---|---|---|"
	for f in "${ITBS[@]}"; do
		printf '| `%s` | %s | `%s` |\n' \
			"$(basename "$f")" \
			"$(du -h "$f" | cut -f1)" \
			"$(sha256sum "$f" | cut -d' ' -f1)"
	done
	echo
	echo "### 刷机前必做"
	echo
	echo '本镜像只有 `config-1` 一个 FIT 配置节点，U-Boot 的 `bootconf` 必须跟着改，'
	echo '否则 `sysupgrade` 重启后引导不了：'
	echo
	echo '```'
	echo 'setenv bootconf config-1'
	echo 'saveenv'
	echo '```'
	echo
	echo '（OpenWrt 的 `sysupgrade` 只负责写 FIT 分区，不会动 `bootconf`。）'
} >>"${GITHUB_STEP_SUMMARY:-/dev/null}"

echo
echo "自检通过，产物就绪。"
